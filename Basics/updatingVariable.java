package Basics;

public class updatingVariable {
    public static void main(String[] args) {
        int x=5;
        System.out.println(x);

         x=7;
        System.out.println(x);

        x=x+6;
        System.out.println(x);

        x=x-23;
        System.out.println(x);

        x=x*-1;
        System.out.println(x);
    }
}
