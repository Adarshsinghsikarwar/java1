package assignmentPractise;

public class basicOperator {
    public static void main(String[] args) {
        int  a = 1;
        System.out.println(a);

        a++;
        System.out.println(a); // increment

        --a;
        System.out.println(a); // decrement

        int b=2;
        System.out.println(a%b); // modulus
    }

}
